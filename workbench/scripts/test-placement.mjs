import assert from 'node:assert/strict';
import {freeStart,boundedTrim,arrangeClips} from '../src/timeline/placement.ts';
const c=(id,start,duration)=>({id,start,duration,inOffset:100,speed:1});
const clips=[c('a',0,100),c('b',150,100),c('c',250,100)];
assert.equal(freeStart(clips,10,40),100);
assert.equal(freeStart(clips,10,60),350);
assert.equal(freeStart(clips,150,100,'b'),150);
assert.equal(freeStart(clips,200,100,'a'),350);
assert.equal(boundedTrim(clips,clips[0],{duration:200}).duration,150);
const trim=boundedTrim(clips,clips[1],{start:50,duration:200,inOffset:0});
assert.deepEqual(trim,{start:100,duration:150,inOffset:50});
const overlapping=[c('a',0,100),c('b',20,50),c('c',200,40)];
assert(arrangeClips(overlapping));assert.deepEqual(overlapping.map(x=>x.start),[0,100,200]);
assert(!arrangeClips(overlapping));
console.log('PASS gap placement, move, trim bounds/source offset, legacy repair, idempotence');
const {insertClip,insertionPoint}=await import('../src/timeline/placement.ts');
const row=[c('a',0,100),c('b',100,50),c('c',150,80)];
assert.equal(insertionPoint(row,'c',20).beforeId,'a');
assert(insertClip(row,row,'c','a'));
assert.deepEqual([...row].sort((a,b)=>a.start-b.start).map(c=>[c.id,c.start]),[['c',0],['a',80],['b',180]]);
assert(insertClip(row,row,'c',null));
assert.deepEqual(row.map(c=>c.start),[0,100,150]);
assert(!insertClip(row,row,'b','c'));
const other=[c('d',0,40),c('e',40,30)];
assert(insertClip(row,other,'b','e'));assert.deepEqual(other.map(c=>[c.id,c.start]),[['d',0],['e',90],['b',40]]);
assert.equal(row.length,2);
const leadingGap=[c('first',90,40),c('second',150,30)];
assert(insertClip(leadingGap,leadingGap,'first','second',0));
assert.deepEqual(leadingGap.map(x=>[x.id,x.start]),[['first',0],['second',150]]);
assert(insertClip(leadingGap,leadingGap,'second','first',0));
assert.deepEqual([...leadingGap].sort((a,b)=>a.start-b.start).map(x=>[x.id,x.start]),[['second',0],['first',140]]);
const lone=[c('only',120,50)];
assert(insertClip(lone,lone,'only',null,0));
assert.equal(lone[0].start,0);
console.log('PASS reorder unequal durations, reverse reorder, no-op, cross-track insertion');
